export const getExerciseById = (id: string): Exercise | undefined => {
  return exercisesDatabase.find(ex => ex.id === id);
};

export const getExercisesByCategory = (category: string): Exercise[] => {
  if (category === 'Todos') return exercisesDatabase;
  if (category === 'Favoritos') {
    const favorites = JSON.parse(localStorage.getItem('gym-tracker-favorites') || '[]');
    return exercisesDatabase.filter(ex => favorites.includes(ex.id));
  }
  return exercisesDatabase.filter(ex => ex.category === category);
};
